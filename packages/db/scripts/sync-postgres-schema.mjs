// Generates prisma/schema.postgresql.prisma from the SQLite schema so the same
// models can target PostgreSQL in production without maintaining two files.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(root, 'prisma/schema.prisma');
const targetPath = resolve(root, 'prisma/schema.postgresql.prisma');

const source = (await readFile(sourcePath, 'utf8')).replace(/\r\n/g, '\n');
const postgres = source.replace(
  /datasource db \{\n(\s*)provider = "sqlite"/,
  'datasource db {\n$1provider = "postgresql"',
);

if (postgres === source) {
  throw new Error('Could not find the SQLite datasource provider in prisma/schema.prisma.');
}

const banner =
  '// Generated by scripts/sync-postgres-schema.mjs from prisma/schema.prisma.\n' +
  '// Do not edit this file directly; edit schema.prisma and run `pnpm db:postgres:sync`.\n\n';

await writeFile(targetPath, `${banner}${postgres}`, 'utf8');
console.log(`Synced ${targetPath}`);
